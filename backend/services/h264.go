package services

// H.264 の「Annex B」形式のバイト列を、最小限だけ読む。
//
// スマホ（ブラウザの WebCodecs）は、1 フレームを 1 メッセージ（= 1 チャンク）として送ってくる。
// チャンクの中は、スタートコード（00 00 01 または 00 00 00 01）で区切られた NAL ユニットが並んでいる。
// NAL の先頭 1 バイトの下位 5 ビットが「種類」で、5 なら IDR（キーフレーム）、7 なら SPS。
// ここでは、キーフレームかどうかを知りたいだけなので、デコードはしない。

const (
	nalIDR = 5 // キーフレーム。ここから先は、これより前のフレームがなくてもデコードできる
)

// hasKeyframe は、チャンクにキーフレーム（IDR）が含まれるかを返す。
// 管理画面（ブラウザ）がデコードを始められるのは、キーフレームからなので、中継ハブが使う。
func hasKeyframe(chunk []byte) bool {
	for i := 0; i+3 < len(chunk); i++ {
		// 00 00 01 を探す（00 00 00 01 も、後ろ 3 バイトがこれに当たる）
		if chunk[i] == 0 && chunk[i+1] == 0 && chunk[i+2] == 1 {
			if chunk[i+3]&0x1f == nalIDR {
				return true
			}
			i += 2
		}
	}
	return false
}
